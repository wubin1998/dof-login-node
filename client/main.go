package main

import (
	"embed"
	"io/fs"
	"os"
	"path/filepath"

	webview2 "github.com/jchv/go-webview2"
)

// The whole UI lives inside the executable. No extra files, no installer.
//
//go:embed web
var webRoot embed.FS

func main() {
	app, err := NewApp()
	if err != nil {
		messageBox("DOF 登录器", "初始化失败：\n"+err.Error())
		return
	}
	defer app.Close()
	app.logf("DOF 登录器启动")

	// Use the Windows 7-compatible WebView2 loader (SDK 109). On Windows 10/11
	// the same loader simply talks to the installed Evergreen runtime.
	app.prepareWebView2Loader()

	web, err := fs.Sub(webRoot, "web")
	if err != nil {
		messageBox("DOF 登录器", "界面资源加载失败：\n"+err.Error())
		return
	}

	url, err := app.StartServer(web)
	if err != nil {
		messageBox("DOF 登录器", "本地界面启动失败：\n"+err.Error())
		return
	}

	dataPath := filepath.Join(app.dataDir, "WebView2")
	if err := os.MkdirAll(dataPath, 0o755); err != nil {
		app.logf("create webview2 data dir: %v", err)
	}

	w := webview2.NewWithOptions(webview2.WebViewOptions{
		Debug:     false,
		AutoFocus: true,
		DataPath:  dataPath,
		WindowOptions: webview2.WindowOptions{
			Title:  "DOF 登录器 · 地下城与勇士",
			Width:  1040,
			Height: 680,
			IconId: 2, // resource id generated by rsrc
			Center: true,
		},
	})
	if w == nil {
		msg := "未检测到 Microsoft Edge WebView2 运行库。\n\n" +
			"Windows 7 / 8：请安装 WebView2 Runtime 109（最后一个支持版本），\n" +
			"并确保系统已安装 SP1 和 KB4474419。\n" +
			"Windows 10 / 11：通常已自带，可尝试通过 Windows 更新修复。\n\n" +
			"是否打开微软官方下载页面？"
		if confirmBox("无法启动界面", msg) {
			openURL("https://developer.microsoft.com/microsoft-edge/webview2/")
		}
		return
	}
	defer w.Destroy()

	setDarkTitleBar(uintptr(w.Window()))
	fitWindow(w)

	app.SetQuit(func() {
		w.Dispatch(func() { w.Terminate() })
	})

	w.Navigate(url)
	w.Run()
	app.logf("DOF 登录器退出")
}
